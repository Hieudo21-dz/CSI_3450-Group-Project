IF DB_ID('FreeBee') IS NULL CREATE DATABASE FreeBee;
GO
USE FreeBee;
GO

DROP TABLE IF EXISTS ORDER_ITEM, ORDERS, MENU_ALLERGEN, CUSTOMER_ALLERGY,
                     MENU_ITEM, CUSTOMER, ALLERGEN;
GO

CREATE TABLE ALLERGEN (
    AllergenID    INT IDENTITY(1,1) CONSTRAINT PK_ALLERGEN PRIMARY KEY,
    AllergenName  VARCHAR(50)   NOT NULL CONSTRAINT UQ_ALLERGEN_NAME UNIQUE,
    SafetyNote    VARCHAR(255)  NULL
);

CREATE TABLE CUSTOMER (
    CustomerID  INT IDENTITY(1,1) CONSTRAINT PK_CUSTOMER PRIMARY KEY,
    FirstName   VARCHAR(50)   NOT NULL,
    LastName    VARCHAR(50)   NOT NULL,
    Phone       VARCHAR(20)   NULL,
    Email       VARCHAR(100)  NOT NULL CONSTRAINT UQ_CUSTOMER_EMAIL UNIQUE
);

CREATE TABLE CUSTOMER_ALLERGY (
    CustomerID  INT          NOT NULL
        CONSTRAINT FK_CA_CUSTOMER REFERENCES CUSTOMER (CustomerID),
    AllergenID  INT          NOT NULL
        CONSTRAINT FK_CA_ALLERGEN REFERENCES ALLERGEN (AllergenID),
    Severity    VARCHAR(10)  NOT NULL
        CONSTRAINT CK_CA_SEVERITY CHECK (Severity IN ('Mild', 'Moderate', 'Severe')),
    CONSTRAINT PK_CUSTOMER_ALLERGY PRIMARY KEY (CustomerID, AllergenID)
);

CREATE TABLE MENU_ITEM (
    MenuItemID  INT IDENTITY(1,1) CONSTRAINT PK_MENU_ITEM PRIMARY KEY,
    ItemName    VARCHAR(100)  NOT NULL CONSTRAINT UQ_MENU_ITEM_NAME UNIQUE,
    Category    VARCHAR(10)   NOT NULL
        CONSTRAINT CK_MENU_CATEGORY CHECK (Category IN ('Appetizer', 'Entree', 'Side', 'Dessert', 'Beverage')),
    Price       DECIMAL(6,2)  NOT NULL CONSTRAINT CK_MENU_PRICE CHECK (Price > 0)
);

CREATE TABLE MENU_ALLERGEN (
    MenuItemID  INT  NOT NULL
        CONSTRAINT FK_MA_MENU_ITEM REFERENCES MENU_ITEM (MenuItemID),
    AllergenID  INT  NOT NULL
        CONSTRAINT FK_MA_ALLERGEN  REFERENCES ALLERGEN (AllergenID),
    CONSTRAINT PK_MENU_ALLERGEN PRIMARY KEY (MenuItemID, AllergenID)
);

CREATE TABLE ORDERS (
    OrderID      INT IDENTITY(1,1) CONSTRAINT PK_ORDERS PRIMARY KEY,
    CustomerID   INT           NOT NULL
        CONSTRAINT FK_ORDERS_CUSTOMER REFERENCES CUSTOMER (CustomerID),
    OrderDate    DATETIME      NOT NULL CONSTRAINT DF_ORDERS_DATE   DEFAULT GETDATE(),
    TotalAmount  DECIMAL(8,2)  NOT NULL CONSTRAINT DF_ORDERS_TOTAL  DEFAULT 0
        CONSTRAINT CK_ORDERS_TOTAL CHECK (TotalAmount >= 0),
    OrderStatus  VARCHAR(10)   NOT NULL CONSTRAINT DF_ORDERS_STATUS DEFAULT 'Pending'
        CONSTRAINT CK_ORDERS_STATUS CHECK (OrderStatus IN ('Pending', 'Confirmed', 'Completed', 'Cancelled'))
);

CREATE TABLE ORDER_ITEM (
    OrderID     INT  NOT NULL
        CONSTRAINT FK_OI_ORDERS    REFERENCES ORDERS (OrderID),
    MenuItemID  INT  NOT NULL
        CONSTRAINT FK_OI_MENU_ITEM REFERENCES MENU_ITEM (MenuItemID),
    Quantity    INT  NOT NULL
        CONSTRAINT CK_OI_QUANTITY CHECK (Quantity BETWEEN 1 AND 50),
    CONSTRAINT PK_ORDER_ITEM PRIMARY KEY (OrderID, MenuItemID)
);
GO
